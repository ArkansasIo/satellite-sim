#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STAFFING = ROOT / "docs" / "staffing-costs.csv"
DEFAULT_OUTPUT = ROOT / "generated" / "planning"

def load_staffing(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for row in rows:
        row["count"] = int(row["count"])
        row["estimated_loaded_cost_cad_per_year"] = int(row["estimated_loaded_cost_cad_per_year"])
    return rows

def build_summary(rows: list[dict]) -> dict:
    result = {}
    for scenario in ("MVP", "Commercial"):
        selected = [r for r in rows if r["scenario"].lower() == scenario.lower()]
        result[scenario] = {
            "headcount": sum(r["count"] for r in selected),
            "annual_loaded_personnel_cost_cad": sum(r["count"] * r["estimated_loaded_cost_cad_per_year"] for r in selected),
            "roles": selected,
        }
    return result

def write_outputs(output: Path, summary: dict) -> None:
    output.mkdir(parents=True, exist_ok=True)
    (output / "program-summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    lines = ["# Generated Program Summary", "", "Generated by tools/file-generator/generate.py", ""]
    for name, data in summary.items():
        lines += ["## " + name, "", "- Headcount: **" + str(data["headcount"]) + "**", "- Annual loaded personnel cost: **$" + format(data["annual_loaded_personnel_cost_cad"], ",") + " CAD**", ""]
    (output / "program-summary.md").write_text("\n".join(lines), encoding="utf-8")
    budget_lines = ["scenario,headcount,annual_personnel_cad,duration_months,personnel_for_duration_cad"]
    for name, data in summary.items():
        months = 12 if name == "MVP" else 24
        duration_cost = round(data["annual_loaded_personnel_cost_cad"] * months / 12)
        budget_lines.append(",".join(map(str, [name, data["headcount"], data["annual_loaded_personnel_cost_cad"], months, duration_cost])))
    (output / "budget-summary.csv").write_text("\n".join(budget_lines) + "\n", encoding="utf-8")
    hiring = ["# Generated Hiring Schedule", "", "Generated from the staffing model.", "", "## MVP", "", "Stage 1: technical lead, C++ simulation, backend/database, frontend/UI, embedded/AVR.", "Stage 2: QA/DevOps and additional engineering capacity.", "", "## Commercial", "", "Add security, additional embedded/backend/frontend, telemetry/data, aerospace, QA, DevOps, product, and technical writing.", ""]
    (output / "hiring-schedule.md").write_text("\n".join(hiring), encoding="utf-8")
    (output / "staffing-generated.json").write_text(json.dumps({"generated_from": "docs/staffing-costs.csv", "scenarios": summary}, indent=2) + "\n", encoding="utf-8")
    manifest = []
    for path in sorted(output.iterdir()):
        if path.is_file() and path.name != "manifest.json":
            manifest.append({"path": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    (output / "manifest.json").write_text(json.dumps({"generator": "tools/file-generator/generate.py", "files": manifest}, indent=2) + "\n", encoding="utf-8")

def main() -> int:
    parser = argparse.ArgumentParser(description="Generate project planning files.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    write_outputs(args.output, build_summary(load_staffing(STAFFING)))
    print("Generated planning package: " + str(args.output))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())